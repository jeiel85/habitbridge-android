const DICT = { ko, en };
let current = 'ko';
export function setLang(l) {
  current = DICT[l] ? l : 'ko';
  return current;
}
export function getLang() {
  return current;
}
export function t(key, params = {}) {
  let s = DICT[current][key] ?? DICT.ko[key] ?? key;
  for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
